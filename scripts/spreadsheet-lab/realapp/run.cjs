  await page.locator('[data-sheet-tab]').nth(0).click({ button: 'right' })
  await page.click('[data-tab-menu] [data-item="moveCopy"]')
  await page.check('[data-move-copy-box]')
  await page.click('[data-move-copy] [data-ok]')
  await page.waitForFunction(() => document.querySelectorAll('[data-sheet-tab]').length === 3)
