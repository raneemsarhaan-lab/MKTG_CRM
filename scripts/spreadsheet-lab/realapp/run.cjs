  const fname = `Lab ${Date.now().toString(36)}`
  await page.click('[data-new-folder]')
  await page.fill('[data-folder-name]', fname)
  await page.keyboard.press('Enter')
  await page.waitForURL(/\/sheets\/[0-9a-f-]{36}/)
  await page.waitForSelector('[data-blank-sheet]')
  const folderUrl = page.url()
