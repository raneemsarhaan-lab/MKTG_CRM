  await cell(page, 0, 0).click()
  await page.keyboard.type('hello')
  await page.keyboard.press('Enter')
  await page.keyboard.type('world')
  await page.keyboard.press('Tab')
  await saved(page)
  ok((await cell(page, 0, 0).innerText()) === 'hello', 'typed into A1')
  ok((await cell(page, 1, 0).innerText()) === 'world', 'Enter moved down to A2')
  await cell(page, 0, 0).dblclick()
  await page.keyboard.press('End'); await page.keyboard.type('!'); await page.keyboard.press('Enter')
  await saved(page)
  ok((await cell(page, 0, 0).innerText()) === 'hello!', 'double-click edits inside the cell')

  console.log('Paste from Excel')
  await cell(page, 2, 1).click()
  await paste(page, 'a\tb\tc\n1\t"x\ny"\t3')
  await saved(page)
  ok((await cell(page, 2, 1).innerText()) === 'a' && (await cell(page, 3, 3).innerText()) === '3', 'TSV pasted as a block')
  ok((await cell(page, 3, 2).innerText()).includes('x') , 'quoted line break kept in one cell')
  ok(await page.locator('[data-blank-sheet] .fx-sheet-td.is-selected, [data-blank-sheet] .fx-sheet-td.is-anchor').count() === 6, 'pasted block selected')

  console.log('Undo, redo, clear')
  await page.keyboard.press('Control+z')
  await saved(page)
  ok((await cell(page, 2, 1).innerText()) === '', 'Ctrl+Z undoes the paste')
  await page.keyboard.press('Control+Shift+z')
  await saved(page)
  ok((await cell(page, 2, 1).innerText()) === 'a', 'Ctrl+Shift+Z redoes it')
  await page.keyboard.press('Delete')
  await saved(page)
  ok((await cell(page, 2, 1).innerText()) === '', 'Delete clears the selection')
  await page.click('[data-undo]')
  await saved(page)
  ok((await cell(page, 2, 1).innerText()) === 'a', 'toolbar Undo')

  console.log('Rows and columns')
  await page.locator('[data-blank-sheet] .fx-sheet-tr[data-row]').nth(0).locator('.fx-sheet-td').nth(0).click({ button: 'right' })
  await page.waitForSelector('[data-cell-menu]')
  await page.click('[data-cell-menu] [data-item="insertRowAbove"]')
  await saved(page)
  ok((await cell(page, 1, 0).innerText()) === 'hello!' && (await cell(page, 0, 0).innerText()) === '', 'Insert row above')
  await page.keyboard.press('Control+z'); await saved(page)
  ok((await cell(page, 0, 0).innerText()) === 'hello!', 'undo the insert')
  await page.locator('[data-blank-sheet] [data-col-head]').nth(1).click({ button: 'right' })
  await page.click('[data-cell-menu] [data-item="deleteCol"]')
  await saved(page)
  ok((await cell(page, 2, 1).innerText()) === 'b', 'Delete column shifts cells left')
  await page.keyboard.press('Control+z'); await saved(page)
  ok((await cell(page, 2, 1).innerText()) === 'a', 'undo brings the column back with its cells')

  console.log('Reload restores')
  await page.reload()
  await page.waitForSelector('[data-blank-sheet]')
  ok((await cell(page, 0, 0).innerText()) === 'hello!' && (await cell(page, 2, 1).innerText()) === 'a', 'cells survive a reload')

  console.log('Tabs')
  await page.click('[data-new-sheet]')
  await page.waitForFunction(() => document.querySelectorAll('[data-sheet-tab]').length === 2)
  ok((await page.locator('[data-sheet-tab][aria-selected="true"]').innerText()).includes('Sheet 2'), '+ adds and opens "Sheet 2"')
  await page.waitForSelector('[data-blank-sheet]')
  await page.locator('[data-sheet-tab]').nth(1).dblclick()
  await page.fill('[data-tab-rename]', 'Budget')
  await page.keyboard.press('Enter')
  await saved(page)
  ok((await page.locator('[data-sheet-tab]').nth(1).innerText()).includes('Budget'), 'double-click renames')
  await page.locator('[data-sheet-tab]').nth(1).click({ button: 'right' })
  await page.waitForSelector('[data-tab-menu]')
  ok(await page.locator('[data-tab-menu] [data-item]').count() >= 8, "Excel's tab menu")
