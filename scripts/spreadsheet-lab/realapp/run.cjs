  await page.waitForFunction(el => el.innerText.includes('Renamed by the sheet lab'), await titleCell.elementHandle(), { timeout: 10000 }).catch(() => {})
  ok((await titleCell.innerText()).includes('Renamed by the sheet lab'), 'a paste fills a linked cell (the task is renamed)')
