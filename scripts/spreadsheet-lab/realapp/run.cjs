  await page.locator('[data-sheet-tab]').nth(0).click()
  await page.waitForSelector('[data-blank-sheet]')
  ok((await cell(page, 0, 0).innerText()) === 'hello!', 'switching back keeps Sheet 1')
  await page.locator('[data-sheet-tab]').nth(1).dragTo(page.locator('[data-sheet-tab]').nth(0), { targetPosition: { x: 4, y: 10 } })
  await saved(page)
  ok((await page.locator('[data-sheet-tab]').nth(0).innerText()).includes('Budget'), 'drag reorders tabs')
  await page.reload()
  await page.waitForSelector('[data-sheet-tab]')
  ok((await page.locator('[data-sheet-tab]').nth(0).innerText()).includes('Budget'), 'tab order survives a reload')
  await page.locator('[data-sheet-tab]').nth(0).click({ button: 'right' })
  await page.click('[data-tab-menu] [data-item="delete"]')
  await page.click('[data-delete-sheet] [data-ok]')
  await saved(page)
  ok(await page.locator('[data-sheet-tab]').count() === 1, 'Delete removes the sheet')
  await page.locator('[data-sheet-tab]').nth(0).click({ button: 'right' })
  ok(await page.locator('[data-tab-menu] [data-item="delete"][aria-disabled="true"]').count() === 1, 'the last sheet cannot be deleted')
  await page.keyboard.press('Escape')

  console.log('Hide, unhide, move or copy, protect')
  await page.click('[data-new-sheet]')
  await page.waitForFunction(() => document.querySelectorAll('[data-sheet-tab]').length === 2)
  await page.waitForSelector('[data-blank-sheet]')
  await page.keyboard.press('Control+PageUp')
  await page.waitForFunction(() => document.querySelector('[data-sheet-tab][aria-selected="true"]')?.textContent?.includes('Sheet 1'))
  ok(true, 'Ctrl+Page Up switches sheets')
