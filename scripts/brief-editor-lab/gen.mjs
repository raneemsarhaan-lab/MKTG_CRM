// Build-time helpers for the lab:
//  1. brief.css: the design tokens and every .fx-brief rule from globals.css,
//     without Tailwind (the lab has no PostCSS step).
//  2. fixtures.gen.ts: every fixtures/*.md as a string, keyed by file name.
import fs from 'node:fs'
import path from 'node:path'

const [ROOT, LAB, OUT] = process.argv.slice(2)
const css = fs.readFileSync(path.join(ROOT, 'src/app/globals.css'), 'utf8')

const roots = [...css.matchAll(/^:root\s*\{[\s\S]*?^\}/gm)].map(m => m[0])
const start = css.indexOf('/* ─── Task brief')
const end   = css.indexOf('/* ─── Utility classes')
if (start < 0 || end < 0) throw new Error('globals.css markers moved: update gen.mjs')
const brief = css.slice(start, end)
fs.writeFileSync(path.join(OUT, 'brief.css'), `${roots.join('\n')}\n\n${brief}`)

const dir = path.join(LAB, 'fixtures')
const fixtures = Object.fromEntries(
  fs.readdirSync(dir).filter(f => f.endsWith('.md') && f !== 'README.md')
    .map(f => [f.replace(/\.md$/, ''), fs.readFileSync(path.join(dir, f), 'utf8')]),
)
fs.writeFileSync(path.join(LAB, 'fixtures.gen.ts'),
  `// Generated by gen.mjs: do not edit.\nexport const FIXTURES: Record<string, string> = ${JSON.stringify(fixtures, null, 2)}\n`)

